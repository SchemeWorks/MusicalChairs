# Exact FAIL lines each control must end with: recorded from the pinned rig by `record`, reviewed in README.md.
EXPECT_FILE = os.path.join(HERE, "expected_fail_lines.txt")


def load_expect():
    exp, cur = {}, None
    if not os.path.exists(EXPECT_FILE):
        return exp
    for line in open(EXPECT_FILE).read().split("\n"):
        if line.startswith("## "):
            cur = line[3:].strip()
            exp[cur] = []
        elif line.startswith("FAIL: ") and cur:
            exp[cur].append(line)
    return exp


def negative_test(c):
    src = open(os.path.join(KEEPER, "test", c["source"] + ".test.mo")).read()
    subject = SUBJECT_IMPORT[c["subject"]]
    assert subject in src, (c["name"], subject)
    text = src.replace(subject, 'import %s "%s";' % (c["subject"], c["name"]))

    def fix(m):
        path = m.group(2)
        if path.startswith("../"):
            path = "../" + path
        elif path == "fixtures":
            path = "../fixtures"
        return 'import %s "%s";' % (m.group(1), path)

    text = re.sub(r'import (\w+) "((?:\.\./)+[\w/]+|fixtures)";', fix, text)
    label = "%s.test.mo (negative control of %s.test.mo)" % (c["name"], c["source"])
    text = text.replace('"%s.test.mo: ' % c["source"], '"%s: ' % label)
    return BANNER_TEST.format(wrong=c["name"], desc=c["desc"], source=c["source"]) + text


def expected_files():
    files = {}
    for c in CONTROLS:
        files[os.path.join(HERE, c["name"] + ".mo")] = c["module"]()
        files[os.path.join(HERE, c["name"] + ".test.mo")] = negative_test(c)
    return files


def cmd_gen():
    for path, text in expected_files().items():
        with open(path, "w") as f:
            f.write(text)
    print("wrote %d files" % len(expected_files()))


def cmd_check():
    bad = 0
    for path, text in expected_files().items():
        cur = open(path).read() if os.path.exists(path) else None
        if cur != text:
            print("STALE: " + os.path.relpath(path, ROOT))
            bad += 1
    # same assertions: a negative test equals its source after undoing the mechanical edits
    for c in CONTROLS:
        neg = open(os.path.join(HERE, c["name"] + ".test.mo")).read()
        src = open(os.path.join(KEEPER, "test", c["source"] + ".test.mo")).read()
        banner = BANNER_TEST.format(wrong=c["name"], desc=c["desc"], source=c["source"])
        assert neg.startswith(banner)
        body = neg[len(banner):]
        undo = body.replace("../../", "../").replace('"../fixtures"', '"fixtures"')
        undo = undo.replace('import %s "%s";' % (c["subject"], c["name"]), SUBJECT_IMPORT[c["subject"]])
        label = "%s.test.mo (negative control of %s.test.mo)" % (c["name"], c["source"])
        undo = undo.replace('"%s: ' % label, '"%s.test.mo: ' % c["source"])
        if undo != src:
            print("ASSERTIONS DIFFER from %s.test.mo: %s" % (c["source"], c["name"]))
            bad += 1
    # API: every public name of the real module is present in the wrong one
    for c in CONTROLS:
        real = c["subject"]
        names = set(n for _, n in re.findall(r"^\s*public (func|let|type) (\w+)", open(os.path.join(KEEPER, real + ".mo")).read(), re.M))
        wrong = set(n for _, n in re.findall(r"^\s*public (func|let|type) (\w+)", open(os.path.join(HERE, c["name"] + ".mo")).read(), re.M))
        if real == "AuthorityTable":
            names = set(n for _, n in re.findall(r"^    public (func|let|type) (\w+)", open(os.path.join(KEEPER, real + ".mo")).read(), re.M))
        missing = names - wrong
        if missing:
            print("API MISSING in %s: %s" % (c["name"], sorted(missing)))
            bad += 1
    if bad:
        sys.exit(1)
    print("negative controls are current: generated files match, assertions identical to the real suites, API complete")


