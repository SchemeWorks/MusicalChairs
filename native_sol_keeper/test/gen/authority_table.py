#!/usr/bin/env python3
"""Generate native_sol_keeper/AuthorityTable.mo from the program IDL.

    python3 native_sol_keeper/test/gen/authority_table.py            # (re)write AuthorityTable.mo
    python3 native_sol_keeper/test/gen/authority_table.py --check    # exit 1 if the file is stale

Source of truth: frontend/src/solana/native/idl/musical_chairs.json (the file
solana/scripts/check-idl.sh keeps equal to a fresh generation). Nothing here
reads the network or the Rust sources.

AUTHORITY RULE (documented in the generated header as well)
-----------------------------------------------------------
For every instruction account the IDL gives (name, signer, writable, optional).
`isAuthority` is true exactly when the account is a SIGNER and its IDL name is
one of AUTHORITY_NAMES:

    authority, upgrade_authority   generic program/upgrade authority
    owner                          a user's position/backer/claim owner
    sponsor                        the genesis/operations sponsor
    recipient                      the management recipient
    governance, g_vault            governance vault (G)
    guardian, p_vault              pause-guardian vault (P)

An account that is NOT a signer is never an authority (a PDA or a validated
reference such as `governance_multisig`, `guardian_multisig`,
`event_authority`, `rng_authority`). Signers that are neither authorities nor
one of NON_AUTHORITY_SIGNERS (`payer`, `sender`: they only pay rent/fees or
fund their own transfer) make `authority.test.mo` fail, so a new IDL signer
name has to be classified on purpose.

The keeper's fee address may only ever sit in a `payer`-named position (rent
for a page it chooses to provision) or be the transaction's fee payer; the
test `fee_address_has_no_program_authority` enforces both.

ACCOUNT DISCRIMINATORS
----------------------
Anchor: account discriminator = sha256("account:<Name>")[:8]. The IDL lists 12
of them; the scheme is verified against all 12 here. RegistryPage and
SnapshotPage are `#[account]` types the keeper must decode but no instruction
names, so the IDL omits them; their discriminators are derived with the same
verified scheme (source: solana/programs/musical_chairs/src/state.rs).
"""
import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
IDL = os.path.join(ROOT, "frontend", "src", "solana", "native", "idl", "musical_chairs.json")
OUT = os.path.join(ROOT, "native_sol_keeper", "AuthorityTable.mo")

AUTHORITY_NAMES = [
    "authority", "upgrade_authority", "owner", "sponsor", "recipient",
    "governance", "g_vault", "guardian", "p_vault",
]
NON_AUTHORITY_SIGNERS = ["payer", "sender"]
EXTRA_ACCOUNT_TYPES = ["RegistryPage", "SnapshotPage"]


def disc(prefix, name):
    return list(hashlib.sha256((prefix + ":" + name).encode()).digest()[:8])


def mo_text(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def mo_bytes(bs):
    return "[" + ", ".join(str(b) for b in bs) + "]"


def mo_bool(b):
    return "true" if b else "false"


def build(idl_bytes):
    idl = json.loads(idl_bytes)
    # Verify the discriminator scheme against the IDL before trusting it for the extras.
    for a in idl["accounts"]:
        assert disc("account", a["name"]) == a["discriminator"], "account discriminator scheme: " + a["name"]
    for i in idl["instructions"]:
        assert disc("global", i["name"]) == i["discriminator"], "instruction discriminator scheme: " + i["name"]

    lines = []
    w = lines.append
    w("/// GENERATED by native_sol_keeper/test/gen/authority_table.py - do not edit.")
    w("/// Source: frontend/src/solana/native/idl/musical_chairs.json")
    w("/// IDL sha256: " + hashlib.sha256(idl_bytes).hexdigest())
    w("///")
    w("/// For every program instruction: each account's (name, isSigner, isWritable,")
    w("/// isOptional, isAuthority). RULE: isAuthority = isSigner AND name in")
    w("/// AUTHORITY_NAMES (" + ", ".join(AUTHORITY_NAMES) + ").")
    w("/// A non-signer is never an authority. Signers outside both sets")
    w("/// (" + ", ".join(NON_AUTHORITY_SIGNERS) + " are the accepted non-authority ones) fail authority.test.mo.")
    w("/// Also carries the 8-byte account discriminators the decoders check.")
    w("module {")
    w("    public let PROGRAM_ID : Text = " + mo_text(idl["address"]) + ";")
    w("    public let IDL_SHA256 : Text = " + mo_text(hashlib.sha256(idl_bytes).hexdigest()) + ";")
    w("")
    w("    public type Account = {")
    w("        name : Text;")
    w("        isSigner : Bool;")
    w("        isWritable : Bool;")
    w("        isOptional : Bool;")
    w("        isAuthority : Bool;")
    w("        /// IDL `address` (system_program), else null.")
    w("        fixedAddress : ?Text;")
    w("    };")
    w("    public type Instruction = { name : Text; discriminator : [Nat8]; accounts : [Account] };")
    w("    public type AccountType = { name : Text; discriminator : [Nat8] };")
    w("")
    w("    public let AUTHORITY_NAMES : [Text] = [" + ", ".join(mo_text(n) for n in AUTHORITY_NAMES) + "];")
    w("    public let NON_AUTHORITY_SIGNERS : [Text] = [" + ", ".join(mo_text(n) for n in NON_AUTHORITY_SIGNERS) + "];")
    w("")
    w("    public let instructions : [Instruction] = [")
    for ix in idl["instructions"]:
        w("        {")
        w("            name = " + mo_text(ix["name"]) + ";")
        w("            discriminator = " + mo_bytes(ix["discriminator"]) + ";")
        w("            accounts = [")
        for a in ix["accounts"]:
            assert "accounts" not in a, "nested account groups are not expected in this IDL"
            signer = bool(a.get("signer", False))
            auth = signer and a["name"] in AUTHORITY_NAMES
            fixed = ("?" + mo_text(a["address"])) if "address" in a else "null"
            w("                { name = %s; isSigner = %s; isWritable = %s; isOptional = %s; isAuthority = %s; fixedAddress = %s }," % (
                mo_text(a["name"]), mo_bool(signer), mo_bool(bool(a.get("writable", False))),
                mo_bool(bool(a.get("optional", False))), mo_bool(auth), fixed))
        w("            ];")
        w("        },")
    w("    ];")
    w("")
    w("    public let accountTypes : [AccountType] = [")
    for a in idl["accounts"]:
        w("        { name = %s; discriminator = %s }," % (mo_text(a["name"]), mo_bytes(a["discriminator"])))
    for n in EXTRA_ACCOUNT_TYPES:
        w("        { name = %s; discriminator = %s }, // derived: sha256(\"account:%s\")[:8]" % (mo_text(n), mo_bytes(disc("account", n)), n))
    w("    ];")
    w("")
    w("    public func instruction(name : Text) : ?Instruction {")
    w("        for (i in instructions.vals()) { if (i.name == name) { return ?i } };")
    w("        null;")
    w("    };")
    w("")
    w("    public func accountDiscriminator(name : Text) : [Nat8] {")
    w("        for (a in accountTypes.vals()) { if (a.name == name) { return a.discriminator } };")
    w("        [];")
    w("    };")
    w("")
    w("    public func isAuthorityName(name : Text) : Bool {")
    w("        for (n in AUTHORITY_NAMES.vals()) { if (n == name) { return true } };")
    w("        false;")
    w("    };")
    w("};")
    return "\n".join(lines) + "\n"


def main():
    idl_bytes = open(IDL, "rb").read()
    text = build(idl_bytes)
    if "--check" in sys.argv:
        current = open(OUT).read() if os.path.exists(OUT) else ""
        if current != text:
            print("AuthorityTable.mo is stale: rerun authority_table.py", file=sys.stderr)
            sys.exit(1)
        print("AuthorityTable.mo is current")
        return
    with open(OUT, "w") as f:
        f.write(text)
    print("wrote", OUT, "(%d instructions)" % len(json.loads(idl_bytes)["instructions"]))


if __name__ == "__main__":
    main()
