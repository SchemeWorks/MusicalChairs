BANNER_MODULE = """/// NEGATIVE CONTROL module (generated by negative.py - do not edit). Written AFTER the implementation.
/// A valid module with the same public API as {real}.mo and ONE deliberate wrong behaviour:
/// {desc}
/// Everything not overridden below is an alias of the real {real}.
"""

SENTINEL_FEE = "".join("\\FE" for _ in range(32))
SENTINEL_SIGNER = "".join("\\AB" for _ in range(32))


def alias_module(real, wrong, desc, overrides, extra_imports=""):
    """A wrapper module: every public name of `real` re-exported, `overrides` replace some."""
    src = open(os.path.join(KEEPER, real + ".mo")).read()
    names = re.findall(r"^    public (func|let|type) (\w+)", src, re.M)
    for name in overrides:
        assert any(n == name for _, n in names), (real, name)
    out = [BANNER_MODULE.format(real=real, desc=desc).rstrip("\n")]
    head = ['import Real "../../%s";' % real] + ([extra_imports] if extra_imports else [])
    body = []
    for kind, name in names:
        if name in overrides:
            body.append(overrides[name].rstrip("\n"))
        elif kind == "type":
            body.append("    public type %s = Real.%s;" % (name, name))
        else:
            body.append("    public let %s = Real.%s;" % (name, name))
    return "\n".join(head) + "\n\n" + out[0] + "\nmodule {\n" + "\n".join(body) + "\n};\n"


