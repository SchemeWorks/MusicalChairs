def compilers():
    moc = os.environ.get("MOC")
    sources = os.environ.get("MOC_SOURCES")
    if not moc or not sources:
        sys.exit("MOC and MOC_SOURCES must be set (source the pinned moc rig env.sh)")
    dfx = os.environ.get("MOC_DFX", os.path.expanduser("~/.cache/dfinity/versions/0.29.2/moc"))
    return [(moc, sources.split()), (dfx, sources.split())]


def run_moc(moc, pkg, path):
    p = subprocess.run([moc, "-r"] + pkg + [os.path.relpath(path, ROOT)], cwd=ROOT, capture_output=True, text=True)
    return p.returncode, p.stdout + p.stderr


def version(moc):
    return subprocess.run([moc, "--version"], capture_output=True, text=True).stdout.strip().split(" (")[0]


REAL_SUITES = ["policy", "journal", "authority", "gate", "pda", "accounts", "tx", "planner"]


def cmd_run():
    expect = load_expect()
    failures = 0
    for moc, pkg in compilers():
        print("##### " + version(moc))
        print("real suites (must be GREEN):")
        for s in REAL_SUITES:
            rc, out = run_moc(moc, pkg, os.path.join(KEEPER, "test", s + ".test.mo"))
            m = re.search(r"^%s\.test\.mo: ALL PASS$" % s, out, re.M)
            tail = m.group(0) if m else "(no ALL PASS line)"
            n_pass = len(re.findall(r"^PASS", out, re.M))
            n_fail = len(re.findall(r"^FAIL", out, re.M))
            ok = rc == 0 and n_fail == 0 and m is not None
            failures += 0 if ok else 1
            print("  %-10s PASS=%-3d FAIL=%d  %s%s" % (s, n_pass, n_fail, tail, "" if ok else "   <-- NOT GREEN"))
        print("negative controls (must END IN A 'FAILED' TRAP with exactly the recorded FAIL lines):")
        for c in CONTROLS:
            rc, out = run_moc(moc, pkg, os.path.join(HERE, c["name"] + ".test.mo"))
            fails = re.findall(r"^FAIL: .*$", out, re.M)
            n_pass = len(re.findall(r"^PASS", out, re.M))
            trap = re.findall(r"explicit trap: (.*check\(s\) FAILED)", out)
            compile_error = re.search(r"(type|syntax|import) error \[M", out)
            problems = []
            if rc == 0:
                problems.append("exit 0 (the wrong variant passed)")
            if "ALL PASS" in out:
                problems.append("printed ALL PASS")
            if compile_error:
                problems.append("compile error - not a valid negative control")
            if not trap:
                problems.append("no 'check(s) FAILED' trap")
            if n_pass == 0:
                problems.append("no check passed at all")
            want = expect.get(c["name"])
            if want is None:
                problems.append("no recorded expectation (run `record` first)")
            elif fails != want:
                problems.append("FAIL lines differ from the record: got %d, recorded %d" % (len(fails), len(want)))
            failures += 1 if problems else 0
            print("  %-38s PASS=%-3d FAIL=%-2d trap: %s%s" % (c["name"], n_pass, len(fails), trap[0] if trap else "-", ("   <-- " + "; ".join(problems)) if problems else ""))
    print("RESULT: " + ("OK" if failures == 0 else "%d problem(s)" % failures))
    sys.exit(0 if failures == 0 else 1)


def cmd_record():
    """Write the observed FAIL lines (primary compiler) to expected_fail_lines.txt for review."""
    moc, pkg = compilers()[0]
    lines = ["# Exact FAIL lines each negative control must end with (recorded from the pinned moc rig by `negative.py record`;",
             "# `negative.py run` compares both compilers against it). Reviewed in README.md."]
    for c in CONTROLS:
        rc, out = run_moc(moc, pkg, os.path.join(HERE, c["name"] + ".test.mo"))
        lines.append("")
        lines.append("## " + c["name"])
        lines += re.findall(r"^FAIL: .*$", out, re.M)
    with open(EXPECT_FILE, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote " + os.path.relpath(EXPECT_FILE, ROOT))


if __name__ == "__main__":
    cmds = {"gen": cmd_gen, "check": cmd_check, "run": cmd_run, "record": cmd_record}
    if len(sys.argv) != 2 or sys.argv[1] not in cmds:
        sys.exit(__doc__)
    cmds[sys.argv[1]]()
