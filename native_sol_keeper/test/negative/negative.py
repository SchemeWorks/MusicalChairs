#!/usr/bin/env python3
"""Negative controls for the watchdog keeper (IMPL-49e, Codex review R5).

    python3 native_sol_keeper/test/negative/negative.py gen     # (re)write the wrong modules and negative tests
    python3 native_sol_keeper/test/negative/negative.py check   # exit 1 if any generated file is stale or an API drifted
    python3 native_sol_keeper/test/negative/negative.py run     # run the real suites and every control, both compilers

`run` needs the pinned rig from the repo root (see README.md): MOC and MOC_SOURCES in the
environment, for example `source <scratchpad>/moc-rig/env.sh`. The second compiler defaults to
dfx 0.29.2's bundled moc (`MOC_DFX` overrides it).

WHAT THIS IS. Each control is a VALID, type-correct module with the same public API as the real one
and ONE deliberate wrong behaviour, run through the SAME assertions as the real suite. The negative
test files are textual copies of `../policy.test.mo` / `../authority.test.mo` in which only import
paths (and the subject module) differ, so the assertions cannot drift apart; `check` proves that. A
control passes when the wrong variant is distinguished: the run ends in the suite's own
"check(s) FAILED" trap with exactly the recorded FAIL lines, and never with a compile error (a missing
module or a type error is NOT evidence).

These were written AFTER the implementation. They are negative controls, not historical
failing-test-first development.
"""
